/// </summary>
public static class MarketingEmailRenderer
{
    /// <summary>바이어 발송용 HTML 이메일을 만든다.</summary>
    public static string BuildHtml(string? buyerName, string? projectTitle, string? bestVariant, string ctaUrl, IReadOnlyList<string>? highlights = null)
    {
