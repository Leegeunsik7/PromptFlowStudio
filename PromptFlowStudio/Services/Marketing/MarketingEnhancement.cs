        var cta = string.IsNullOrWhiteSpace(ctaUrl) ? "#" : ctaUrl;

        return "<!doctype html><html><body style=\"margin:0;background:#f1f5f9;font-family:Segoe UI,Arial,sans-serif\">" +
            "<table role=\"presentation\" width=\"100%\" cellpadding=\"0\" cellspacing=\"0\"><tr><td align=\"center\" style=\"padding:24px\">" +
            "<table role=\"presentation\" width=\"600\" cellpadding=\"0\" cellspacing=\"0\" style=\"background:#fff;border-radius:14px;overflow:hidden;box-shadow:0 8px 30px rgba(0,0,0,.08)\">" +
            "<tr><td style=\"background:linear-gradient(135deg,#0ea5e9,#6366f1);padding:26px 28px\"><h1 style=\"margin:0;color:#fff;font-size:22px\">🎬 PromptFlow Studio</h1>" +
            "<p style=\"margin:6px 0 0;color:#e0e7ff;font-size:13px\">AI-crafted B2B promotional video</p></td></tr>" +
            $"<tr><td style=\"padding:26px 28px\"><p style=\"font-size:15px;color:#0f172a\">Dear <b>{Esc(buyer)}</b>,</p>" +
            $"<p style=\"font-size:14px;color:#334155;line-height:1.6\">We are pleased to share <b>{Esc(title)}</b>, produced entirely with our offline AI media studio.</p>" +
            (string.IsNullOrWhiteSpace(bestVariant) ? "" : $"<p style=\"font-size:14px;color:#334155\">Recommended style for your market: <b style=\"color:#6366f1\">{Esc(bestVariant)}</b></p>") +
            $"<ul style=\"padding-left:18px\">{hi}</ul>" +
            $"<p style=\"text-align:center;margin:26px 0 8px\"><a href=\"{Esc(cta)}\" style=\"background:linear-gradient(135deg,#0ea5e9,#6366f1);color:#fff;text-decoration:none;font-weight:700;font-size:15px;padding:13px 28px;border-radius:10px;display:inline-block\">▶ Watch the promo</a></p></td></tr>" +
