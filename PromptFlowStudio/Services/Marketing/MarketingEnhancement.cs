            "</table></td></tr></table></body></html>";
    }

    private static IReadOnlyList<string> DefaultHighlights() => new[]
    {
        "Same-day AI generation — no agency lead time",
        "Multi-language dubbing (EN/DE/ZH/JA) in one click",
        "3D CAD hologram + telemetry HUD for technical proof",
    };

    private static string Esc(string? s) => (s ?? "").Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("\"", "&quot;");
}

/// <summary>캠페인 로그 1건 — 시각·유형·상세·결과.</summary>
public sealed record CampaignLogEntry(string Time, string Type, string Detail, string Result);

/// <summary>
/// [PromptFlowStudio] 캠페인 세션 로그 추출기(v3.5.0 자율 발상 · static · 순수 BCL).
///   ▸ 발행 결과 + A/B 예측을 <b>캠페인 로그</b>(CSV/Markdown)로 추출 — 배포 감사·성과 리포트.
/// </summary>
public static class CampaignLogExtractor
{
    /// <summary>발행 결과 + A/B 리포트 → 캠페인 로그 엔트리.</summary>
    public static IReadOnlyList<CampaignLogEntry> BuildEntries(IEnumerable<PublishResult>? publishes, AbReport? ab)
    {
        var now = DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture);
        var list = new List<CampaignLogEntry>();
        if (ab is not null)
            foreach (var v in ab.Variants)
                list.Add(new CampaignLogEntry(now, "AB-PREDICT", $"{v.Name} (종합 {v.OverallScore})", v.Key == ab.BestVariantKey ? "BEST" : "candidate"));
        foreach (var p in publishes ?? Array.Empty<PublishResult>())
            list.Add(new CampaignLogEntry(now, "PUBLISH", $"{p.Target} ({p.StatusCode})", p.Ok ? "OK" : "FAIL"));
        return list;
    }

    /// <summary>로그 → CSV.</summary>
    public static string RenderCsv(IReadOnlyList<CampaignLogEntry> entries)
    {
        var sb = new StringBuilder("time,type,detail,result\n");
        foreach (var e in entries) sb.Append($"{Csv(e.Time)},{Csv(e.Type)},{Csv(e.Detail)},{Csv(e.Result)}\n");
        return sb.ToString();
    }

    /// <summary>로그 → Markdown 표.</summary>
    public static string RenderMarkdown(IReadOnlyList<CampaignLogEntry> entries)
    {
        var sb = new StringBuilder("| 시각 | 유형 | 상세 | 결과 |\n|---|---|---|---|\n");
        foreach (var e in entries) sb.Append($"| {e.Time} | {e.Type} | {e.Detail} | {e.Result} |\n");
        return sb.ToString();
    }

    private static string Csv(string s) => s.Contains(',') || s.Contains('"') ? "\"" + s.Replace("\"", "\"\"") + "\"" : s;
}
